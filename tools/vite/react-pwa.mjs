import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

async function filesAt(folder, relative = '') {
  const entries = await readdir(path.join(folder, relative), { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;
    const child = path.posix.join(relative, entry.name);
    if (entry.isDirectory()) files.push(...await filesAt(folder, child));
    else files.push('/' + child);
  }
  return files;
}

/** Emit a scoped cache-first worker for the generated React suite and its same-origin document engines. */
export function reactPwa() {
  let outputDirectory;
  return {
    name: 'vibeoffice-react-pwa',
    configResolved(config) { outputDirectory = path.resolve(config.root, config.build.outDir); },
    async closeBundle() {
      if (!outputDirectory) return;
      const output = outputDirectory;
      const assets = (await filesAt(output)).filter((file) => file !== '/sw.js');
      const version = Date.now().toString(36);
      const source = `/* Generated by tools/vite/react-pwa.mjs. */\n'use strict';\nconst CACHE = 'vibeoffice-react-${version}';\nconst ASSETS = ${JSON.stringify(assets)};\nconst cached = (path) => caches.match(new URL(path, self.location.origin).href);\nself.addEventListener('install', (event) => event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)).then(() => self.skipWaiting())));\nself.addEventListener('activate', (event) => event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((key) => key.startsWith('vibeoffice-react-') && key !== CACHE).map((key) => caches.delete(key)))).then(() => self.clients.claim())));\nself.addEventListener('fetch', (event) => { const request = event.request; const url = new URL(request.url); if (request.method !== 'GET' || url.origin !== self.location.origin) return; if (request.mode === 'navigate') { const path = url.pathname.endsWith('/') ? url.pathname + 'index.html' : url.pathname; event.respondWith((async () => (await cached(path)) || (await cached('/index.html')) || fetch(request))()); return; } if (ASSETS.includes(url.pathname)) event.respondWith(cached(url.pathname).then((response) => response || fetch(request))); });\n`;
      await writeFile(path.join(output, 'sw.js'), source);
    },
  };
}
